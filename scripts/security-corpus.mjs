import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, mkdtempSync, rmSync, copyFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dispositions } from './security-dispositions.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const destination = join(root, 'tests/fixtures/security');
const xmlCommit = 'c79c9612fcc77b06b0d16f35fd363d938bdbbf5e';
const xsltCommit = '81cbfb53bb1bc034853058ff896203d108b663cc';
const dirs = ['test/errors', 'test/errors10', 'test/recurse', 'test/XPath'];
const extra = ['test/valid/766956.xml', 'test/valid/dtds/766956.dtd', 'Copyright'];
const hash = bytes => createHash('sha256').update(bytes).digest('hex');

export function safePath(path) {
  assert(path && !path.includes('\\') && !path.startsWith('/'));
  assert(path.split('/').every(part => part && part !== '.' && part !== '..'));
  return path;
}

export function inventory(nvd, debian) {
  const entries = new Map();
  function entry(id, product, source) {
    assert.match(id, /^CVE-\d{4}-\d+$/);
    const row = entries.get(id) ?? { id, products: [], sources: [], references: [] };
    for (const [field, value] of [['products', product], ['sources', source]]) {
      if (!row[field].includes(value)) row[field].push(value);
    }
    entries.set(id, row);
    return row;
  }
  for (const [product, data] of Object.entries(nvd)) {
    assert.equal(data.totalResults ?? data.vulnerabilities.length, data.vulnerabilities.length,
      'all NVD pages must be present');
    for (const { cve } of data.vulnerabilities) {
      const row = entry(cve.id, product.replace(/^cpe-/, ''), 'nvd');
      row.description = cve.descriptions.find(value => value.lang === 'en')?.value;
      assert(row.description, cve.id);
      row.published = cve.published;
      row.status = cve.vulnStatus;
      row.references = [...new Set([...row.references, ...cve.references.map(value => value.url)])].sort();
    }
  }
  for (const product of ['libxml2', 'libxslt', 'xmlsec1']) {
    for (const [id, value] of Object.entries(debian[product] ?? {})) {
      if (!id.startsWith('CVE-')) continue;
      const row = entry(id, product === 'xmlsec1' ? 'xmlsec' : product, 'debian');
      row.description ??= value.description;
    }
  }
  return [...entries.values()].sort((a, b) => a.id.localeCompare(b.id));
}

function files(directory, prefix = '') {
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const path = prefix + entry.name;
    return entry.isDirectory() ? files(join(directory, entry.name), `${path}/`) : [path];
  }).sort();
}

export function audit(data) {
  const rows = dispositions(data.records);
  assert(rows.every(row => row.disposition), 'every advisory needs an explicit disposition');
  return `${JSON.stringify({
    advisorySha256: hash(Buffer.from(JSON.stringify(data))),
    records: rows.map(({ id, disposition }) => ({ id, ...disposition })),
  }, null, 2)}\n`;
}

export function report(data) {
  const rows = dispositions(data.records);
  assert(rows.every(row => row.disposition));
  const counts = new Map();
  for (const { disposition: { status } } of rows) counts.set(status, (counts.get(status) ?? 0) + 1);
  const unavailable = rows.filter(row => row.disposition.status === 'insufficient-public-detail');
  const lines = ['# CVE Inventory', '',
    'Generated by `node scripts/security-corpus.mjs report`; see [audit scope and methods](cve-audit.md).', '',
    `Snapshot: ${data.auditedAt}. This is a source-scoped inventory, not a claim that every CVE is reproduced.`, '',
    ...[...counts].sort().map(([status, count]) => `- ${status}: ${count}`), '',
    '## Unqualified Public Triggers', '',
    'The following records remain unresolved as individual reproductions. Public descriptions/references',
    'were retained, but no exact trigger was qualified. This does not prove that no public data exists,',
    'and does not mean non-applicability or successful security coverage.', '',
    ...unavailable.map(row => `- [${row.id}](https://nvd.nist.gov/vuln/detail/${row.id}): ${row.description.replace(/\s+/g, ' ')}`), '',
    '## Per-Advisory Disposition', '',
    'Reasons and source references are in the [machine-readable audit](../tests/fixtures/security/audit.json)',
    'and [advisory snapshot](../tests/fixtures/security/advisories.json).', '',
    '| Advisory | Search products | Disposition | Mechanism / evidence |',
    '| --- | --- | --- | --- |',
    ...rows.map(row => {
      const { status, mechanism, evidence } = row.disposition;
      const link = evidence.startsWith('https://') ? evidence : `../${evidence}`;
      return `| [${row.id}](https://nvd.nist.gov/vuln/detail/${row.id}) | ${row.products.join(', ')} | ${status} | [${mechanism}](${link}) |`;
    }), '',
  ];
  return lines.join('\n');
}

async function importCorpus(source, dataDir, xsltSource) {
  const temp = mkdtempSync(join(tmpdir(), 'xml-security-corpus-'));
  try {
    const archive = execFileSync('git', ['-C', source, 'archive', xmlCommit, ...dirs, ...extra],
      { maxBuffer: 32 * 1024 * 1024, env: { ...process.env, GIT_NO_REPLACE_OBJECTS: '1' } });
    execFileSync('tar', ['-xf', '-', '-C', temp], { input: archive });
    const imported = files(temp);
    const manifest = imported.map(path => `${hash(readFileSync(join(temp, path)))}\t${path}`);
    const upstream = join(destination, 'libxml2');
    mkdirSync(upstream, { recursive: true });
    for (const path of imported) {
      mkdirSync(dirname(join(upstream, path)), { recursive: true });
      copyFileSync(join(temp, path), join(upstream, path));
    }
    writeFileSync(join(destination, 'files.tsv'), `${manifest.join('\n')}\n`);
    const xsltPaths = ['Copyright', 'tests/security/input.xml', 'tests/security/load_document.xsl',
      'tests/security/write_output.xsl', 'tests/security/xinclude_doc.xml', 'tests/security/secret.xml'];
    const xsltManifest = [];
    for (const path of xsltPaths) {
      const bytes = execFileSync('git', ['-C', xsltSource, 'show', `${xsltCommit}:${path}`],
        { env: { ...process.env, GIT_NO_REPLACE_OBJECTS: '1' } });
      mkdirSync(dirname(join(destination, 'libxslt', path)), { recursive: true });
      writeFileSync(join(destination, 'libxslt', path), bytes);
      xsltManifest.push(`${hash(bytes)}\t${path}`);
    }
    writeFileSync(join(destination, 'xslt-files.tsv'), `${xsltManifest.join('\n')}\n`);
    const samlCommit = '46578df0695269a16f1c94171f1429873f90ed99';
    const samlManifest = [];
    for (const path of ['LICENSE', 'tests/xmlsec1-keydata/signed-assertion-random-embedded-cert.xml',
      'tests/xmlsec1-keydata/signed-assertion-with-hmac.xml',
      'tests/xmlsec1-keydata/signed-response-with-hmac.xml']) {
      const url = `https://raw.githubusercontent.com/IdentityPython/pysaml2/${samlCommit}/${path}`;
      const response = await fetch(url);
      assert(response.ok, `${url}: ${response.status}`);
      const bytes = Buffer.from(await response.arrayBuffer());
      mkdirSync(dirname(join(destination, 'pysaml2', path)), { recursive: true });
      writeFileSync(join(destination, 'pysaml2', path), bytes);
      samlManifest.push(`${hash(bytes)}\t${path}\t${url}`);
    }
    writeFileSync(join(destination, 'pysaml2-files.tsv'), `${samlManifest.join('\n')}\n`);
    const nvd = Object.fromEntries(['libxml2', 'libxslt', 'xmlsec', 'libxml', 'cpe-libxml2', 'cpe-libxslt'].map(product => [product,
      JSON.parse(readFileSync(join(dataDir, `xml-sec-nvd-${product}.json`)))]));
    const debianBytes = readFileSync(join(dataDir, 'xml-sec-cve-tracker.json'));
    writeFileSync(join(destination, 'advisories.json'), `${JSON.stringify({
      auditedAt: '2026-10-22',
      sources: {
        nvd: 'https://services.nvd.nist.gov/rest/json/cves/2.0',
        debian: 'https://security-tracker.debian.org/tracker/data/json',
        debianSha256: hash(debianBytes),
        queries: Object.fromEntries(Object.entries(nvd).map(([product, data]) => [product, {
          selector: product.startsWith('cpe-')
            ? `virtualMatchString=cpe:2.3:a:xmlsoft:${product.slice(4)}` : `keywordSearch=${product}`,
          timestamp: data.timestamp, totalResults: data.totalResults,
          sha256: hash(readFileSync(join(dataDir, `xml-sec-nvd-${product}.json`))),
        }])),
      },
      xmlCommit,
      xsltCommit,
      records: inventory(nvd, JSON.parse(debianBytes)),
    }, null, 2)}\n`);
  } finally {
    rmSync(temp, { recursive: true, force: true });
  }
}

function check() {
  const manifest = readFileSync(join(destination, 'files.tsv'), 'utf8').trim().split('\n');
  const expected = manifest.map(line => {
    const [digest, path, extra] = line.split('\t');
    assert.equal(extra, undefined);
    safePath(path);
    assert.equal(hash(readFileSync(join(destination, 'libxml2', path))), digest, path);
    return path;
  }).sort();
  assert.deepEqual(files(join(destination, 'libxml2')), expected, 'no missing or unlisted payloads');
  const data = JSON.parse(readFileSync(join(destination, 'advisories.json')));
  assert.equal(data.xmlCommit, xmlCommit);
  assert.equal(data.xsltCommit, xsltCommit);
  const xsltPaths = readFileSync(join(destination, 'xslt-files.tsv'), 'utf8').trim().split('\n').map(line => {
    const [digest, path] = line.split('\t');
    safePath(path);
    assert.equal(hash(readFileSync(join(destination, 'libxslt', path))), digest);
    return path;
  });
  assert.deepEqual(files(join(destination, 'libxslt')), xsltPaths.sort());
  const samlPaths = readFileSync(join(destination, 'pysaml2-files.tsv'), 'utf8').trim().split('\n').map(line => {
    const [digest, path, url] = line.split('\t');
    safePath(path);
    assert(url.startsWith('https://raw.githubusercontent.com/IdentityPython/pysaml2/46578df0695269a16f1c94171f1429873f90ed99/'));
    assert.equal(hash(readFileSync(join(destination, 'pysaml2', path))), digest);
    return path;
  });
  assert.deepEqual(files(join(destination, 'pysaml2')), samlPaths.sort());
  assert.equal(new Set(data.records.map(row => row.id)).size, data.records.length);
  for (const row of dispositions(data.records)) {
    assert(row.disposition, `missing disposition: ${row.id}`);
    const evidence = row.disposition.evidence;
    if (!evidence.startsWith('https://')) readFileSync(join(root, safePath(evidence)));
  }
  assert.equal(readFileSync(join(destination, 'audit.json'), 'utf8'), audit(data), 'stale audit report');
  assert.equal(readFileSync(join(root, 'docs/cve-inventory.md'), 'utf8'), report(data), 'stale inventory report');
  console.log(`${data.records.length} advisory records; ${expected.length} upstream files verified`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv[2] === 'import') {
    assert(process.argv[3] && process.argv[4] && process.argv[5],
      'import LIBXML2_SOURCE NVD_AND_DEBIAN_DIRECTORY LIBXSLT_SOURCE');
    await importCorpus(resolve(process.argv[3]), resolve(process.argv[4]), resolve(process.argv[5]));
  } else if (process.argv[2] === 'report') {
    const data = JSON.parse(readFileSync(join(destination, 'advisories.json')));
    writeFileSync(join(destination, 'audit.json'), audit(data));
    writeFileSync(join(root, 'docs/cve-inventory.md'), report(data));
  } else {
    assert.equal(process.argv[2], '--check');
    check();
  }
}
